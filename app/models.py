from datetime import datetime, timezone
from werkzeug.security import generate_password_hash, check_password_hash
from flask_login import UserMixin
from flask_sqlalchemy import SQLAlchemy

db = SQLAlchemy()


class User(UserMixin, db.Model):
    """User account model for Residents and Administrators."""
    __tablename__ = 'users'

    id = db.Column(db.Integer, primary_key=True)
    full_name = db.Column(db.String(120), nullable=False)
    email = db.Column(db.String(120), unique=True, nullable=False, index=True)
    password_hash = db.Column(db.String(255), nullable=False)
    role = db.Column(db.String(20), nullable=False, default='resident')  # 'admin' or 'resident'
    avatar = db.Column(db.String(255), nullable=True, default=None)
    created_at = db.Column(db.DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationships
    energy_records = db.relationship('EnergyRecord', backref='user', lazy='dynamic', cascade='all, delete-orphan')
    predictions = db.relationship('Prediction', backref='user', lazy='dynamic', cascade='all, delete-orphan')
    activity_logs = db.relationship('ActivityLog', backref='user', lazy='dynamic')

    def set_password(self, password: str):
        """Hash and store the user's password securely."""
        self.password_hash = generate_password_hash(password)

    def check_password(self, password: str) -> bool:
        """Verify the user's password against the stored hash."""
        return check_password_hash(self.password_hash, password)

    @property
    def is_admin(self) -> bool:
        """Check if user has administrative privileges."""
        return self.role == 'admin'

    @property
    def avatar_url(self) -> str:
        """Return the user's avatar URL or default placeholder."""
        if self.avatar:
            return f"/static/uploads/avatars/{self.avatar}"
        return "/static/images/default_avatar.svg"

    def __repr__(self):
        return f'<User {self.email} ({self.role})>'


class EnergyRecord(db.Model):
    """Historical and manually entered residential energy consumption records."""
    __tablename__ = 'energy_records'

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey('users.id', ondelete='CASCADE'), nullable=False, index=True)
    date = db.Column(db.Date, nullable=False, index=True)
    electricity_consumption_kwh = db.Column(db.Float, nullable=False)
    peak_consumption_kwh = db.Column(db.Float, nullable=False, default=0.0)
    off_peak_consumption_kwh = db.Column(db.Float, nullable=False, default=0.0)
    estimated_cost = db.Column(db.Float, nullable=False, default=0.0)
    appliance_usage_hours = db.Column(db.Float, nullable=False, default=0.0)
    is_synthetic = db.Column(db.Boolean, default=False, nullable=False)  # Labeled as Demo Data
    created_at = db.Column(db.DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    @property
    def consumption_level(self) -> str:
        """Categorize consumption into Low, Moderate, or High."""
        from app.utils.helpers import get_system_thresholds
        low_th, mod_th = get_system_thresholds()
        if self.electricity_consumption_kwh <= low_th:
            return 'Low'
        elif self.electricity_consumption_kwh <= mod_th:
            return 'Moderate'
        return 'High'

    def to_dict(self):
        return {
            'id': self.id,
            'user_id': self.user_id,
            'user_name': self.user.full_name if self.user else 'Unknown',
            'date': self.date.strftime('%Y-%m-%d'),
            'electricity_consumption_kwh': round(self.electricity_consumption_kwh, 2),
            'peak_consumption_kwh': round(self.peak_consumption_kwh, 2),
            'off_peak_consumption_kwh': round(self.off_peak_consumption_kwh, 2),
            'estimated_cost': round(self.estimated_cost, 2),
            'appliance_usage_hours': round(self.appliance_usage_hours, 1),
            'is_synthetic': self.is_synthetic,
            'consumption_level': self.consumption_level
        }

    def __repr__(self):
        return f'<EnergyRecord User:{self.user_id} Date:{self.date} kWh:{self.electricity_consumption_kwh}>'


class Prediction(db.Model):
    """Energy consumption predictions generated by the Artificial Neural Network."""
    __tablename__ = 'predictions'

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey('users.id', ondelete='CASCADE'), nullable=False, index=True)
    prediction_date = db.Column(db.Date, nullable=False, index=True)
    predicted_consumption_kwh = db.Column(db.Float, nullable=False)
    estimated_cost = db.Column(db.Float, nullable=False, default=0.0)
    peak_consumption_kwh = db.Column(db.Float, nullable=True)
    off_peak_consumption_kwh = db.Column(db.Float, nullable=True)
    appliance_usage_hours = db.Column(db.Float, nullable=True)
    consumption_level = db.Column(db.String(20), nullable=False, default='Moderate')  # Low, Moderate, High
    model_version = db.Column(db.String(50), nullable=True)
    created_at = db.Column(db.DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    def to_dict(self):
        return {
            'id': self.id,
            'user_id': self.user_id,
            'user_name': self.user.full_name if self.user else 'Unknown',
            'prediction_date': self.prediction_date.strftime('%Y-%m-%d'),
            'predicted_consumption_kwh': round(self.predicted_consumption_kwh, 2),
            'estimated_cost': round(self.estimated_cost, 2),
            'appliance_usage_hours': round(self.appliance_usage_hours, 1) if self.appliance_usage_hours else None,
            'consumption_level': self.consumption_level,
            'created_at': self.created_at.strftime('%Y-%m-%d %H:%M:%S')
        }

    def __repr__(self):
        return f'<Prediction User:{self.user_id} TargetDate:{self.prediction_date} Pred_kWh:{self.predicted_consumption_kwh}>'


class ANNModel(db.Model):
    """Metadata, training statistics, and accuracy metrics of the trained ANN models."""
    __tablename__ = 'ann_models'

    id = db.Column(db.Integer, primary_key=True)
    model_name = db.Column(db.String(100), nullable=False)
    training_date = db.Column(db.DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
    training_records = db.Column(db.Integer, nullable=False, default=0)
    test_records = db.Column(db.Integer, nullable=False, default=0)
    mae = db.Column(db.Float, nullable=False, default=0.0)      # Mean Absolute Error
    mse = db.Column(db.Float, nullable=False, default=0.0)      # Mean Squared Error
    rmse = db.Column(db.Float, nullable=False, default=0.0)     # Root Mean Squared Error
    r2_score = db.Column(db.Float, nullable=False, default=0.0) # R² Coefficient of Determination
    model_file = db.Column(db.String(255), nullable=False)
    status = db.Column(db.String(20), nullable=False, default='Active')  # 'Active', 'Archived', 'Failed'
    notes = db.Column(db.Text, nullable=True)

    def __repr__(self):
        return f'<ANNModel {self.model_name} R2:{self.r2_score:.4f} Status:{self.status}>'


